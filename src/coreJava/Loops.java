package coreJava;

public class Loops {

	public static void main(String[] args) {
		// for-loop
		for(int i=1; i<=3; i++) {
			System.out.println(i);
		}
		
		//while-loop
		int j=1;
		while(j<=3) {
			System.out.println(j);
			j++;
		}
		
		//do-while
		int k=1;
		do{
			System.out.println(k);
			k++;
		} while(k<=3);
	}

}
