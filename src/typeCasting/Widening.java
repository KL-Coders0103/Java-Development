package typeCasting;

public class Widening {
  public static void main(String[] args) {
        
    //widening type casting  automatically happend    
          int num =10;
          
          System.out.println("data type of num: "+num  );
          
          double val  =  num;  
          
          System.out.println("data type of num: "+ val  );
          
          
          
          byte x='A';
          byte y=65;
          System.out.println(" x: "+x);
          System.out.println(" y: "+y);
          
          

    }
}
